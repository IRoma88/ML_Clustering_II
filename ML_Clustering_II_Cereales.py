"""#Ejercicio 1 dendograma

Realiza el dendograma para agrupar los cereales en función de su valor nutricional.
"""

import scipy.cluster.hierarchy as sch

X = cereals.iloc[:, 1:].values

dendograma = sch.dendrogram(sch.linkage(X, method = 'ward'))
plt.title('Dendograma')
plt.xlabel('Cereales')
plt.ylabel('Distancia Euclidiana')
plt.show()

"""¿Cuantos grupos diferentes se obserban en el dendograma? Almacena la respuesta como número entero en la variable res1"""

