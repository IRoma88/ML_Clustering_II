"""#Ejercicio 2 Clustering Aglomerativo

Vamos a crear el modelo de clusterring aglomerativo de sklearn con n_clusters igual al observado en el dendograma.
"""

# Importamos el algoritmo de sklearn
from sklearn.cluster import AgglomerativeClustering

ac = AgglomerativeClustering(n_clusters = 3, metric = 'euclidean', linkage = 'ward')
y_hc = ac.fit_predict(X)

#Visualizar los clusters
plt.scatter(X[y_hc == 0, 0], X[y_hc == 0, 1], s = 100, c = 'red', label = 'Cluster 1')
plt.scatter(X[y_hc == 1, 0], X[y_hc == 1, 1], s = 100, c = 'blue', label = 'Cluster 2')
